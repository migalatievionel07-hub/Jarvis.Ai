@app.route("/register", methods=["GET", "POST"])
def register():
    error = None

    if request.method == "POST":
        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")
        confirm = request.form.get("confirm", "")

        if len(username) < 3:
            error = "Username must contain at least 3 characters."
        elif len(password) < 6:
            error = "Password must contain at least 6 characters."
        elif password != confirm:
            error = "Passwords do not match."
        else:
            db = get_db()
            try:
                cursor = db_execute(
                    db,
                    "INSERT INTO users (username, password) VALUES (?, ?) RETURNING id",
                    (username, generate_password_hash(password))
                )
                user_id = cursor.fetchone()["id"]
                db.commit()
                session["user_id"] = user_id
                session["username"] = username
                return redirect(url_for("home"))
            except (sqlite3.IntegrityError, psycopg.errors.UniqueViolation):
                db.rollback()
                error = "That username already exists."
            finally:
                db.close()

    return render_template_string(
        AUTH_HTML, title="CREATE ACCOUNT", error=error, register=True
    )


@app.route("/login", methods=["GET", "POST"])
def login():
    error = None

    if request.method == "POST":
        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")

        db = get_db()
        try:
            user = db_execute(
                db, "SELECT * FROM users WHERE username = ?", (username,)
            ).fetchone()
        finally:
            db.close()

        if user and check_password_hash(user["password"], password):
            session["user_id"] = user["id"]
            session["username"] = user["username"]
            return redirect(url_for("home"))

        error = "Incorrect username or password."

    return render_template_string(
        AUTH_HTML, title="LOGIN", error=error, register=False
    )


@app.route("/logout")
def logout():
    session.clear()
    return redirect(url_for("login"))


@app.route("/ask", methods=["POST"])
def ask():
    if "user_id" not in session:
        return jsonify({"reply": "Please log in first."}), 401

    data = request.get_json(silent=True) or {}
    message = str(data.get("message", "")).strip()

    if not message:
        return jsonify({"reply": "Please enter a message."}), 400

    db = get_db()
    try:
        user_id = session["user_id"]

        db_execute(
            db,
            "INSERT INTO messages (user_id, role, message) VALUES (?, ?, ?)",
            (user_id, "YOU", message)
        )
        db.commit()

        history_rows = db_execute(
            db,
            """SELECT role, message FROM messages
               WHERE user_id = ? ORDER BY id ASC""",
            (user_id,)
        ).fetchall()

        reply = ask_ai(message, history_rows)

        db_execute(
            db,
            "INSERT INTO messages (user_id, role, message) VALUES (?, ?, ?)",
            (user_id, "JARVIS", reply)
        )
        db.commit()
    finally:
        db.close()

    return jsonify({"reply": reply})


@app.route("/history")
def history():
    if "user_id" not in session:
        return jsonify({"error": "Please log in."}), 401

    db = get_db()
    try:
        rows = db_execute(
            db,
            """SELECT role, message, created_at FROM messages
               WHERE user_id = ? ORDER BY id ASC""",
            (session["user_id"],)
        ).fetchall()
    finally:
        db.close()

    return jsonify([
        {
            "role": row["role"],
            "message": row["message"],
            "created_at": (
                str(row["created_at"]) if row["created_at"] else None
            )
        }
        for row in rows
    ])


@app.route("/upload", methods=["POST"])
def upload():
    if "user_id" not in session:
        return jsonify({"reply": "Please log in first."}), 401

    file = request.files.get("file")
    if not file or not file.filename:
        return jsonify({"reply": "Choose a file first."}), 400

    filename = secure_filename(file.filename)
    if not filename:
        return jsonify({"reply": "Invalid filename."}), 400

    # The file is acknowledged but not stored or analyzed yet.
    return jsonify({
        "reply": (
            f"File selected: {filename}. "
            "Content analysis is not configured yet."
        )
    })


