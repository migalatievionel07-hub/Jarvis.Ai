# ---------- DATABASE ----------

def get_db():
    """Use PostgreSQL on Render when DATABASE_URL is set; otherwise SQLite."""
    if DATABASE_URL:
        return psycopg.connect(
            DATABASE_URL,
            row_factory=dict_row,
            connect_timeout=10
        )

    db = sqlite3.connect(DB)
    db.row_factory = sqlite3.Row
    return db


def db_execute(db, sql, params=()):
    """Use the correct parameter placeholder for the selected database."""
    if DATABASE_URL:
        sql = sql.replace("?", "%s")
    return db.execute(sql, params)


def init_db():
    db = get_db()
    try:
        if DATABASE_URL:
            db.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username TEXT UNIQUE NOT NULL,
                    password TEXT NOT NULL
                )
            """)
            db.execute("""
                CREATE TABLE IF NOT EXISTS messages (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id),
                    role TEXT NOT NULL,
                    message TEXT NOT NULL,
                    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
                )
            """)
        else:
            db.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    username TEXT UNIQUE NOT NULL,
                    password TEXT NOT NULL
                )
            """)
            db.execute("""
                CREATE TABLE IF NOT EXISTS messages (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    user_id INTEGER NOT NULL,
                    role TEXT NOT NULL,
                    message TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """)
        db.commit()
    finally:
        db.close()


init_db()


# ---------- AI ----------

@lru_cache(maxsize=1)
def get_ai():
    from freelm import FreeLLM
    return FreeLLM.from_env(keyless=True)


def ask_ai(message, history):
    conversation = "\n".join(
        f"{row['role']}: {row['message']}"
        for row in history[-12:]
    )

    prompt = f"""
You are JARVIS, a helpful virtual assistant.
Answer in the language used by the user.
Be clear, friendly, and honest.
Never claim to control real devices.

Previous conversation:
{conversation}

User: {message}
JARVIS:
"""

    try:
        answer = get_ai().text(prompt)
        answer = str(answer).strip() if answer else ""
        return answer or "I could not generate an answer."
    except Exception:
        app.logger.exception("AI request failed")
        return (
            "I cannot connect to the AI service right now. "
            "Please try again later."
        )


